# What this file does (plain words): writes the one-page controls table of COLOUR AND FADE only (setting name, socket name in Blender, what it
# does, range, default), straight from the layer file so the table can never disagree with the code. Run inside Blender:
#   tests/blender.sh tests/colour_and_fade/make_my_controls_table.py
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(HERE, '..', '..', 'layers')))
import layer_interface as li  # noqa: E402
import colour_and_fade  # noqa: E402

GROUPS = [
    ('The palette and the tints (colours; typed as web hex codes, converted to Blender\'s linear numbers for you)', ['tone_1', 'tone_2', 'tone_3', 'tone_4', 'tone_5', 'tone_6', 'tone_7', 'tone_8', 'tone_9', 'green_tint', 'warm_tint', 'patch_tint', 'tint_']),
    ('Between slates: each slate\'s own base tone', ['tone_centre', 'tone_spread', 'outlier_']),
    ('Inside a slate: the fade, the tongues, the patches and the specks', ['fade_', 'streak_', 'top_darkening', 'speck_', 'patch_hardness', 'edge_ragged']),
    ('Across slates: sun-bleached and damp patches, slow drift', ['bleach_', 'stain_', 'patch_size', 'drift_amount']),
    ('Finish and the other outputs', ['grain_amount', 'tone_height', 'tone_roughness']),
]
rows = li.controls_table_rows(colour_and_fade.LAYER_KEY, colour_and_fade.CONTROLS, with_common=True, default_seed=colour_and_fade.DEFAULT_SEED)


def fmt(value):
    return f'{value:g}' if isinstance(value, float) else str(value)


lines = ['# COLOUR AND FADE - the controls (one page)', '',
         'Every control is a setting named `colour_and_fade.<name>` (in `recipe/settings.json`, or passed to a bake, for example `--params \'{"colour_and_fade.fade_amount": 0.5}\'`)',
         'and a knob on the layer\'s box in the Shader editor. Order of strength: default in `layers/colour_and_fade.py` < `recipe/settings.json` < the bake\'s parameters.',
         'Sizes are TILE units (1.0 = the whole base tile; at 1254 dots per tile 0.012 = 15 dots). "Tone step" = one step along the palette (about 11 of 255 in brightness).',
         'Generated by `tests/colour_and_fade/make_my_controls_table.py` from the layer file.', '']
used = set()
lines += ['## Every layer has these two', '', '| setting | socket in Blender | default | low | high | what it does |', '|---|---|---|---|---|---|']
for r in rows:
    if r[0] in ('colour_and_fade.seed', 'colour_and_fade.amount'):
        lines.append(f'| `{r[0]}` | {r[1]} | {fmt(r[2])} | {fmt(r[3])} | {fmt(r[4])} | {r[5]} |')
        used.add(r[0])
lines.append('')
for title, prefixes in GROUPS:
    lines += [f'## {title}', '', '| setting | socket in Blender | default | low | high | what it does |', '|---|---|---|---|---|---|']
    for r in rows:
        key = r[0].split('.', 1)[1]
        if r[0] in used:
            continue
        if any(key.startswith(p) for p in prefixes):
            low = fmt(r[3]) if r[3] is not None else ''
            high = fmt(r[4]) if r[4] is not None else ''
            lines.append(f'| `{r[0]}` | {r[1]} | {fmt(r[2])} | {low} | {high} | {r[5]} |')
            used.add(r[0])
    lines.append('')
left = [r[0] for r in rows if r[0] not in used]
assert not left, f'controls missing from the groups: {left}'
lines += ['Declared links: none (this layer reads only the layout bundle: piece_id, local_x, local_y, piece_width, piece_height, piece_mask).', '']
with open(os.path.join(HERE, 'controls_colour_and_fade.md'), 'w') as handle:
    handle.write('\n'.join(lines))
print('wrote controls_colour_and_fade.md with', len(rows), 'controls')
