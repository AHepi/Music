import bpy
ng=bpy.data.node_groups.new("t",'GeometryNodeTree')
def show(idn,**kw):
    n=ng.nodes.new(idn)
    for k,v in kw.items(): setattr(n,k,v)
    print(idn,kw,"IN",[(s.name,s.identifier,s.type,s.enabled) for s in n.inputs],"OUT",[(s.name,s.type,s.enabled) for s in n.outputs])
