# What this file does (plain words)
# ---------------------------------------------------------------------------------------------------------------------------------------------
# Writes masks/CONTRACT.md from names.py (the list of bus names) and, when packs exist, each mask's real numbers from the manifests (min, mean, max in each scene's pack and the
# frame each scene's pack supplies it from). The contract is generated so it can never disagree with the code:
#     python3 -I masks/make_contract.py
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
KIT_ROOT = os.path.abspath(os.path.join(HERE, '..'))
sys.path.insert(0, KIT_ROOT)
sys.dont_write_bytecode = True

from apply import dials as dials_module  # noqa: E402
from masks import names  # noqa: E402

FRAMES = [
    ('GP', 'ground plan', 'A picture of the ground seen from above (4 cm per dot; 2 cm for the fine ones). Looked up by the dot\'s WORLD x and y. Outside the picture the default is returned.'),
    ('WF', 'wall sheet', 'One picture per wall mesh (50 dots per metre across, 2 cm; the 8 cm coarse ones for broad fields), looked up by the dot\'s position in the OBJECT\'s own frame (across the front, up from the floor). Chosen by the object value `wk_frame_id`. Counts only where the surface faces the sheet\'s front (within about 25 degrees): `frame_valid`. Where it does not (gable ends, chimneys, roofs) the ground-plan version or the default is used.'),
    ('TX', 'texture space', 'The photo material\'s own picture coordinates: cavity, joint line and cell number of the set\'s brick, stone and flag pictures (period in metres from the set file).'),
    ('SH', 'shader', 'Made inside the shader from position and normal; nothing is stored.'),
]


def pack_stats():
    out = {}
    for path in sorted(glob.glob(os.path.join(KIT_ROOT, 'masks', 'packs', '*', '*', 'manifest.json'))):
        manifest = json.load(open(path))
        key = f"{manifest['set']}/{manifest['scene']}"
        out[key] = manifest
    return out


def main():
    packs = pack_stats()
    lines = []
    w = lines.append
    w('# The mask contract: every name a layer can read')
    w('')
    w('*Generated by `masks/make_contract.py` from `masks/names.py` and the packs\' manifests. Do not edit by hand; change `names.py` and run the generator.*')
    w('')
    w('## How a layer asks for a mask')
    w('')
    w('A layer is one node group. To read a mask it declares a float input called `M <Name In Title Case>` (`moss_site` becomes `M Moss Site`; `names.mask_socket(name)` makes it). That is all: the bus (`masks/bus.py`) builds one node group, `WK MASKS <material>`, per material, holding only the masks the layers on that material asked for, and wires them by name. A layer never knows which picture, frame or set a mask comes from. A mask the set has not made returns its **default** (the table below), so a layer that reads `M Water Dist` in a set without water simply sees "no water".')
    w('')
    w('Every mask is a number from 0 to 1 unless the meaning says metres. Distances are scaled so 1 = "far enough that it no longer matters" (the reach is in the meaning).')
    w('')
    w('## The frames')
    w('')
    w('| frame | what it is | how it is looked up |')
    w('|---|---|---|')
    for code, title, text in FRAMES:
        w(f'| `{code}` | {title} | {text} |')
    w('')
    w('A name lists the frame(s) that can supply it. `GP/WF` means: on a wall the wall sheet is used where it applies, otherwise the ground plan; `WF/GP` the other way round. `OBJ` values are per object (below).')
    w('')
    w('## Every bus name')
    w('')
    sets = list(packs)
    header = '| name | frame | default | meaning |' + ''.join(f' range in {s} |' for s in sets)
    w(header)
    w('|---|---|---|---|' + '---|' * len(sets))
    for name, frame, default, meaning in names.NAMES:
        cells = []
        for s in sets:
            st = (packs[s].get('mask_stats') or {}).get(name)
            entry = (packs[s].get('masks') or {})
            supplied = [f for f, table in entry.items() if name in table]
            if st:
                cells.append(f"{st['min']:.2f} to {st['max']:.2f} (mean {st['mean']:.2f}) from {'+'.join(supplied)}")
            elif supplied:
                cells.append('from ' + '+'.join(supplied))
            else:
                cells.append('default')
        w(f"| `{name}` | {frame} | {default} | {meaning} |" + ''.join(f' {c} |' for c in cells))
    w('')
    w('The name `socket` of each is `names.mask_socket(name)`. `names.BY_NAME[name]` gives the row; `names.default_of(name)` the default.')
    w('')
    w('## What the scale helper hands every layer (`WK SCALE`, `WK MARK WIDTH`)')
    w('')
    w('Every mark is sized in **plate dots** (one dot of the plate picture the painter repaints; its size is the `plate.size` of the set file), turned into metres from the camera. The runner sets `Dot Angle` for each picture from the camera and the plate height (a 540 x 960 test picture uses the plate\'s value, so a mark has the same physical size in a small picture as in the plate). A layer declares any of these as inputs and the bus wires them:')
    w('')
    w('| input name | meaning |')
    w('|---|---|')
    w('| `Dot Across` | metres per plate dot across the view at this point = depth x Dot Angle x Painter Widen |')
    w('| `Dot Along` | how long a dot is along the way the surface leans away = Dot Across / max(\\|normal . view direction\\|, 0.12) |')
    w('| `Fade Near` | 1 near the camera, 0 far (Fade Start to Fade End metres; fine detail gives way to the layer\'s AVERAGE tone, never to clean) |')
    w('| `Far Blend` | 0 near, 1 far (Handover Start to Handover End: 3D pieces stop and the painted far band takes over) |')
    w('| `Distance`, `Cos View` | straight distance in metres; \\|normal . view direction\\| |')
    w('')
    w('`Painter Widen` = 0.5 / painter scale (x1.11 at 0.45, x1.25 at 0.40). `WK MARK WIDTH` (inputs Real Width, Min Dots, Dot Size, Inflate Limit; outputs Width, Fade) keeps a mark from being thinner than its minimum in dots, and fades it to the layer\'s average tone once the widening passes the limit.')
    w('')
    w('## Per-object values (custom properties, read with an Attribute node of type Object)')
    w('')
    w('The kit never edits meshes or material slots. Everything per object is a custom property, written by `apply/seed.py` (tested: EEVEE and Cycles read it equally; a missing property reads 0):')
    w('')
    w('| property | meaning |')
    w('|---|---|')
    w('| `wk_seed` | 0..1 from the object\'s rounded world position (1 cm) and its role: renaming an object or rebuilding does not reshuffle |')
    w('| `wk_role_id` | the place of the object\'s role in the set\'s role list, from 1 (0 = no role) |')
    w('| `wk_frame_id` | which wall sheet the object reads (0 = none); written when a pack is loaded |')
    w('| `wk_zmin`, `wk_zmax` | the object\'s own height range in world z |')
    w('| `wk_<flag>` | per-object facts a picture cannot know, from the set file\'s `flags` block (for example `wk_stepped`) |')
    w('| `wk_<layer>_amount` | 1 on the roles the layer acts on, 0 on every other object (so a material shared by two kinds of object is weathered only where the set says) |')
    w('| `wk_<layer>_<dial>` | the role\'s multiplier for a dial the set varies by role (1 where the role has none) |')
    w('')
    w('## The layer\'s own sockets (see `apply/layer_template.py`)')
    w('')
    w('In: the bundle `Colour`, `Roughness`, `Specular IOR Level`, `Coat Weight`, `Normal`, `Metallic`, `Wet Normal`; the masks by name; `Wet Mask`, `Puddle Mask` (a layer placed after the water layer gets them; slot A reads 0); the scale inputs; the dials, one input each in Title Case (`Amount`, `Seed`, `Inflate Limit`, `Fade Start`, `Fade End`, `Wet Follow`, then the layer\'s own). Out: the same bundle (an output left unconnected passes its input through) and `Mask` (the layer\'s own mask, raw, for debug views and the measures).')
    w('')
    w('Dials: 12 layers, 152 rows in `apply/dial_table.json` (generated from the plan\'s one list; the look files carry the values).')
    w('')
    w('## Shared rules')
    w('')
    for line in (
        '**Exact zero.** `moss_site`, `weed_site` and `lichen_site` are exactly 0.0 wherever `footfall` is 0.6 or more, `crown` 0.7 or more or `keepclear` 0.5 or more (`algae_site` where `keepclear` is 0.5 or more). A habitat field is a product with a gate, never a threshold on noise, so the zero is exact; the reader tests it when it builds the pack.',
        '**Amount 0 changes nothing.** Every mix factor in a layer is a product containing the amount; nothing can become NaN.',
        '**No Bevel, Ambient Occlusion or Pointiness nodes.** Edges come from `edge_dist`, `piece_gap` and `step_edge` (made from the real geometry, once).',
        '**Frames.** A mask is only as sharp as its frame: GP 4 cm (fine 2 cm), WF 2 cm (coarse 8 cm), TX the photo\'s own pixels.'):
        w('* ' + line)
    w('')
    out = os.path.join(HERE, 'CONTRACT.md')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print('wrote', out, len(lines), 'lines;', len(names.NAMES), 'names;', len(packs), 'packs')


if __name__ == '__main__':
    main()
